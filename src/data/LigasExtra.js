function expandir([id, nombre, corto, idioma, nivel, camiseta, acento, estampado, liga]) {
  const h = hashString(id);
  const [att, mid, def] = NIVEL[nivel];
  const kit = (shirt, accent, pattern, shorts, socks, num) => ({ shirt, accent, pattern, shorts, socks, num });
  const sobre = estampado === 'solid' ? camiseta : acento;
  return {
    id, name: nombre, short: corto, flavor: idioma, att, mid, def,
    home: kit(camiseta, acento, estampado, sobre, camiseta, acento),
    away: kit('#f4f4f4', camiseta, 'solid', '#f4f4f4', camiseta, acento),
    crest: { shape: ESCUDO[h % ESCUDO.length], emblem: EMBLEMA[(h >>> 3) % EMBLEMA.length], mono: corto.slice(0, 2) },
    style: {
      formation: FORMACIONES[h % FORMACIONES.length],
      mentality: [-1, 0, 1][(h >>> 12) % 3],
      width: 0.6, depth: 0.5,
      pressing: 0.4 + ((h >>> 4) % 5) * 0.1,
      tempo: 0.4 + ((h >>> 7) % 5) * 0.1,
      line: 0.4 + ((h >>> 10) % 4) * 0.1,
    },
    tagline: `Club de ${LIGA_DE[liga].nombre.toLowerCase()}`,
    liga,
  };
}

/** Definiciones de los clubes extra (mismo formato que TEAM_DEFS). */
export function clubesExtra() {
  for (const l of LIGAS_EXTRA) l.clubes = [];
  for (const c of CLUBES) LIGA_DE[c[8]].clubes.push(c[0]);
  return CLUBES.map(expandir);
}
