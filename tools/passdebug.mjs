import { TEAMS } from '../src/data/TeamsData.js';
import { tacticsFromStyle } from '../src/match/Tactics.js';
import { Match } from '../src/match/Match.js';
import { STATE, SIM_DT } from '../src/core/Config.js';
const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, '').split('=')));
const home = TEAMS[+(args.h || 0)], away = TEAMS[+(args.a || 3)];
const m = new Match({ home, away, homeTactics: tacticsFromStyle(home.style), awayTactics: tacticsFromStyle(away.style), difficulty: args.diff || 'normal', halfMinutes: 5, userSide: null, seed: +(args.seed || 7) });
let cur = null; const res = {};
const add = (type, out) => { res[type] = res[type] || {}; res[type][out] = (res[type][out] || 0) + 1; };
const close = (out) => { if (cur) { add(cur.type, out); if (args.v && cur.type===args.v) console.log(cur.type, out, 'd=' + cur.d.toFixed(1), 'v=' + cur.speed.toFixed(1), 'u=' + cur.u.toFixed(0), cur.tgt, 'dt=' + (m.clock - cur.t).toFixed(2)); cur = null; } };
m.on('kick', (d) => { close('rekick:' + d.type); const b = m.ball; const t = b.passTarget; cur = { type: d.type, t: m.clock, team: d.player.team, d: t ? Math.hypot(t.x - b.x, t.z - b.z) : 0, speed: d.speed, u: d.player.u, tgt: t ? t.role : '-' }; });
m.on('control', (d) => { if (cur) close(d.player.team === cur.team ? 'OK' : 'rival'); });
m.on('out', (d) => close('fuera:' + d.kind));
m.on('offside', () => close('fdj'));
m.on('goal', () => close('gol'));
m.on('save', () => close('parada'));
m.on('foul', () => close('falta'));
let steps = 0;
while (m.state !== STATE.FULL_TIME && steps++ < 200000) m.step(SIM_DT);
for (const k in res) console.log(k.padEnd(8), JSON.stringify(res[k]));
console.log(m.teams[0].score, m.teams[1].score);
